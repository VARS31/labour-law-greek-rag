"""Write docs/missing-laws.md: laws our chunks mention but don't contain, and documents that are only a title.

The fetch list for Phase 6. Also looks through the other 46 volumes of the dataset, because some laws missing from
the labour volume are there.

Usage: .venv/bin/python -I scripts/missing_laws.py
"""

import collections
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from labour_rag.chunking import NOTE_SHARE, OVERLAP, note_words  # noqa: E402
from labour_rag.dataset import LABOUR_VOLUME, load_documents  # noqa: E402
from labour_rag.header import parse_header  # noqa: E402
from labour_rag.law_mentions import find_mentions, label, resolve  # noqa: E402
from labour_rag.normalize import fold, normalize  # noqa: E402

CHUNKS = ROOT / "data/processed/labour_chunks.jsonl"
RAW = ROOT / "data/raw/greek_legal_code"
REPORT = ROOT / "docs/missing-laws.md"
SNIPPET = 45       # characters shown on each side of an example mention


def own_text(chunk):
    """The chunk's text without the words it repeats from the window before it, so overlaps aren't counted twice."""
    if chunk["part"] and chunk["part"] > 1:
        return " ".join(chunk["text"].split()[OVERLAP:])
    return chunk["text"]


def snippet(text, mention):
    folded = fold(text)
    start, end = max(0, mention.start - SNIPPET), mention.end + SNIPPET
    return "…" + folded[start:end].replace("|", "/") + "…"


def other_volumes():
    """{(abbr, number): {year: {volume, …}}} for every numbered act outside the labour volume."""
    found = collections.defaultdict(lambda: collections.defaultdict(set))
    for doc in load_documents(RAW):
        if doc["volume_id"] == LABOUR_VOLUME:
            continue
        meta = parse_header(normalize(doc["text"][:800]))
        if meta["act_abbr"] and meta["act_number"]:
            found[meta["act_abbr"], meta["act_number"]][meta["year"]].add(doc["volume"])
    return found


def volumes_of(law, elsewhere):
    abbr, number, year = law
    years = elsewhere.get((abbr, number), {})
    if year is None:
        names = {v for vols in years.values() for v in vols} if len(years) == 1 else set()
    else:
        names = {v for y, vols in years.items() if y and abs(y - year) <= 1 for v in vols}
    return sorted(names)


def after_title(chunk):
    """What follows the header and title in a one-chunk document."""
    text, title = chunk["text"], chunk["title"] or ""
    position = text.find(title) if title else -1
    if position < 0:
        return text
    return text[position + len(title):].lstrip(" .,;:»«")


def title_only_documents(chunks):
    """Documents with nothing after the title, or only an editorial note ("Κατηργήθη δια …", "Βλ. κατωτ. …")."""
    documents = collections.defaultdict(list)
    for chunk in chunks:
        documents[chunk["doc_id"]].append(chunk)
    found = []
    for pieces in documents.values():
        if len(pieces) > 1:
            continue
        chunk = pieces[0]
        rest = after_title(chunk)
        if not rest.strip():
            found.append({"chunk": chunk, "kind": "title only", "rest": ""})
        elif note_words(rest) >= NOTE_SHARE * len(rest.split()) or re.match(r"(?:Βλ\.|Βλέπε|Άρθρον? μόνον?\.?\s*\()", rest):
            found.append({"chunk": chunk, "kind": "title and a note", "rest": rest})
    return found


def write_report(chunks, found, missing, elsewhere, stubs, mention_count):
    in_data = sum(len(v) for v in found.values())
    not_in_data = sum(len(v) for v in missing.values())
    ranked = sorted(missing.items(), key=lambda kv: (-len(kv[1]), kv[0][1], kv[0][0]))
    with_volume = [(law, volumes_of(law, elsewhere)) for law, _ in ranked]
    in_other = sum(bool(v) for _, v in with_volume)
    out = ["# Missing laws: the fetch list for Phase 6", "",
           "This file is generated by [`scripts/missing_laws.py`](../scripts/missing_laws.py). Don't edit it by hand.",
           "", f"Our {len(chunks):,} labour chunks mention numbered laws and decrees {in_data + not_in_data:,} times. "
           f"{in_data:,} of those mentions point to {len(found):,} laws we have. The other {not_in_data:,} point to "
           f"**{len(missing):,} laws that are not a document in our data**. They are listed below, most mentioned "
           f"first.", "",
           f"{in_other:,} of the missing laws are in another volume of the same dataset, so they can be fetched without "
           "looking anywhere else. The last column names the volume. For the rest we need another source.", "",
           f"**{len(stubs):,} documents in our data are only a title**, or a title and an editorial note. Their rules "
           "aren't in the data either, so they belong on the fetch list too (second table).", "",
           "## How this was counted", "",
           "- **What counts as a mention:** Ν., Ν.Δ., Α.Ν., Π.Δ. and Β.Δ. followed by a number, in any of the forms the "
           "texts use (`Νόμ. 435/1976`, `Ν.Δ. 4020/59`, `Νόμ. 2556/23-24 Δεκ. 1997`, `υπ’ αριθ. 748/66 Β.Δ/τος`, "
           "`ν. 2112`). Words repeated by overlapping chunks are counted once.",
           "- **What is left out:** ministerial decisions (Υ.Α., Κ.Υ.Α.); decrees cited only by date (`Β.Δ. 16/18 Ιουλ. "
           "1920`), because the first number is a day; laws numbered in Greek letters (`ν. ΔΛ΄`).",
           "- **Same law:** type and number match and the year is at most 1 away, because a law may be voted one year "
           "and published the next. Mentions without a year take the year of a matching document, or the only year "
           "other mentions give. If no year is known and the number is under 100, the mention is dropped, because "
           "too many such matches aren't laws.",
           "- **Printing errors stay as written:** for example `Ν. 4435/1976`, a misprint of Ν. 435/1976, gets its own "
           "row. So a few rows are not real laws.",
           "- **Other volumes:** found by reading the header of every document in the other 46 volumes. A blank cell "
           "doesn't prove a law is absent, because some headers can't be read.",
           "- **Title only:** a document of one chunk with nothing after its title, or only an editorial note such as "
           "`Κατηργήθη δια …`. A one-sentence decision whose whole content is its title counts too.", "",
           "## Laws mentioned but not in our data", "",
           "| # | Law | Mentions | Documents | Example chunk | In another volume |", "|---:|---|---:|---:|---|---|"]
    for i, (law, volumes) in enumerate(with_volume, 1):
        payloads = missing[law]
        first = min(payloads, key=lambda p: p["id"])
        out.append(f"| {i} | {label(*law)} | {len(payloads)} | {len({p['doc_id'] for p in payloads})} | "
                   f"`{first['id']}`: {first['snippet']} | {', '.join(volumes)} |")
    out += ["", "## Documents in our data that are only a title", "",
            "Ranked by how often other chunks mention them; those with no mentions follow by number of words. "
            "`is_stub` in the chunks file only marks documents under 30 words, so this list is longer: it also catches "
            "longer titles, such as Π.Δ. 305/1996 at 32 words, and titles followed only by a note.", "",
            "| # | Chunk | Source | Mentions | Words | What it holds | Title |", "|---:|---|---|---:|---:|---|---|"]
    stubs = sorted(stubs, key=lambda s: (-mention_count(s["chunk"]), s["chunk"]["words"], s["chunk"]["id"]))
    for i, stub in enumerate(stubs, 1):
        c = stub["chunk"]
        source = c["citation"] if not c["citation_fallback"] else f"{c['act_abbr'] or 'Act'} ({c['year']})"
        title = (c["title"] or "").replace("|", "/")
        title = title if len(title) <= 110 else title[:110] + "…"
        note = stub["kind"] if not stub["rest"] else f"{stub['kind']}: {stub['rest'][:70].replace('|', '/')}"
        out.append(f"| {i} | `{c['id']}` | {source} | {mention_count(c)} | {c['words']} | {note} | {title} |")
    REPORT.write_text("\n".join(out) + "\n", encoding="utf-8")


def main():
    chunks = [json.loads(line) for line in CHUNKS.open(encoding="utf-8")]
    documents = {(c["act_abbr"], str(c["act_number"]), c["year"]) for c in chunks
                 if c["act_abbr"] and c["act_number"] and not c["citation_fallback"]}
    mentions = []
    for chunk in chunks:
        text = own_text(chunk)
        for mention in find_mentions(text):
            mentions.append((mention, {"id": chunk["id"], "doc_id": chunk["doc_id"],
                                       "snippet": snippet(text, mention)}))
    found, missing = resolve(mentions, documents)

    def mention_count(chunk):
        key = (chunk["act_abbr"], str(chunk["act_number"]), chunk["year"])
        return sum(p["doc_id"] != chunk["doc_id"] for p in found.get(key, []))

    stubs = title_only_documents(chunks)
    write_report(chunks, found, missing, other_volumes(), stubs, mention_count)
    print(f"{len(missing)} missing laws, {sum(len(v) for v in missing.values())} mentions; {len(stubs)} title-only "
          f"documents; wrote {REPORT}")


if __name__ == "__main__":
    main()
